const isImage = (url = '') => /\.(jpg|jpeg|png|gif|webp|svg|heic|heif)(?:\?.*)?$/i.test(url) || url.startsWith('blob:') || url.startsWith('data:image/');
const isVideo = (url = '') => /\.(mp4|webm|ogg)(?:\?.*)?$/i.test(url) || url.startsWith('blob:') || url.startsWith('data:video/');
const isAudio = (url = '') => /\.(mp3|wav|m4a|aac|ogg|webm|opus)(?:\?.*)?$/i.test(url) || url.startsWith('blob:') || url.startsWith('data:audio/');

const formatDateTime = (value) => {
  if (!value) return 'N/A';
  return new Date(value).toLocaleString();
};

const stripNotificationTags = (message = '') =>
  String(message)
    .replace(/\[(requestId|salaryId|tx):[^\]]+\]/gi, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

const extractTaggedId = (message, tag) => {
  const match = String(message || '').match(new RegExp(`\\[${tag}:(\\d+)\\]`, 'i'));
  return match ? Number(match[1]) : null;
};

